const { chromium } = require('C:/Users/son/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  const checks = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, pass, detail) => { checks.push({ name, pass, detail }); console.log(`${pass ? 'PASS' : 'FAIL'} ${name}`, detail ?? ''); };
  const url = process.env.VERIFY_URL || 'http://127.0.0.1:5173';
  const out = __dirname;
  await page.goto(`${url}/#environment`);
  const buttons = page.locator('.environment-achievement__button');
  await buttons.first().waitFor();
  await buttons.nth(1).scrollIntoViewIfNeeded();
  await buttons.nth(1).click();
  await page.waitForTimeout(150);
  const middle = await page.locator('.environment-achievement__panel').evaluateAll(nodes => nodes.map(n => ({ moving: n.dataset.moving, height: n.getBoundingClientRect().height, hidden: n.hidden, expanded: n.getAttribute('aria-hidden') === 'false' })));
  check('Achievement animates between states', middle.filter(n => n.moving === 'true').length >= 1, middle);
  await page.waitForTimeout(1100);
  check('Only chosen panel remains open', await page.locator('.environment-achievement__panel:not([hidden])').count() === 1);
  check('Second achievement selected', await buttons.nth(1).getAttribute('aria-expanded') === 'true');
  await buttons.nth(2).click();
  await page.waitForTimeout(70);
  await buttons.first().click();
  await page.waitForTimeout(1100);
  check('Rapid interrupted change settles correctly', await buttons.first().getAttribute('aria-expanded') === 'true' && await page.locator('.environment-achievement__panel:not([hidden])').count() === 1);
  await buttons.first().focus();
  await page.keyboard.press('ArrowDown');
  check('Achievement arrow keyboard navigation', await buttons.nth(1).evaluate(n => document.activeElement === n));
  await page.screenshot({ path: path.join(out, 'achievement-desktop.png') });

  await page.goto(`${url}/#others`);
  const cloud = page.locator('[data-other-achievement]').first();
  await cloud.scrollIntoViewIfNeeded();
  await page.mouse.move(5, 5);
  await page.waitForTimeout(300);
  const before = await cloud.locator('.other-achievement__hanging').evaluate(n => n.style.transform);
  await page.waitForTimeout(750);
  const after = await cloud.locator('.other-achievement__hanging').evaluate(n => n.style.transform);
  check('Cloud breeze moves while visible', before !== after && await cloud.getAttribute('data-cloud-moving') === 'true', {before, after});
  await cloud.locator('.other-achievement__hanging').hover({position:{x:30,y:100},force:true});
  await page.waitForTimeout(600);
  check('Cloud responds to pointer', (await cloud.locator('.other-achievement__shrub').evaluate(n => n.style.transform)) !== '');
  await page.screenshot({ path: path.join(out, 'clouds-desktop.png') });
  await page.locator('#others').evaluate(n => { n.scrollTop = 0; });
  await page.waitForTimeout(400);
  check('Clouds pause offscreen', await cloud.getAttribute('data-cloud-moving') === 'false');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await cloud.scrollIntoViewIfNeeded();
  await page.waitForTimeout(250);
  check('Reduced-motion clouds static', await cloud.getAttribute('data-cloud-moving') === 'false' && await cloud.locator('.other-achievement__hanging').evaluate(n => n.style.transform === ''));
  await page.goto(`${url}/#environment`);
  await buttons.nth(1).click();
  check('Reduced-motion achievement settles immediately', await page.locator('.environment-achievement__panel[data-moving="true"]').count() === 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await buttons.nth(2).click();
  await page.locator('.environment-achievement__panel:not([hidden]) img').evaluateAll(images => Promise.all(images.map(image => image.decode())));
  await page.screenshot({ path: path.join(out, 'achievement-mobile.png') });
  check('Mobile panel fits viewport', await page.locator('#environment').evaluate(n => n.scrollWidth <= n.clientWidth + 1));
  await page.goto(`${url}/#others`);
  await cloud.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'cloud-mobile.png') });
  check('Mobile clouds fit viewport', await page.locator('#others').evaluate(n => n.scrollWidth <= n.clientWidth + 1));
  check('No runtime errors', errors.length === 0, errors);
  const result = { passed: checks.every(c => c.pass), checks, errors };
  fs.writeFileSync(path.join(out, 'details-results.json'), JSON.stringify(result, null, 2));
  await browser.close();
  if (!result.passed) process.exitCode = 1;
})().catch(error => { console.error(error); process.exit(1); });
